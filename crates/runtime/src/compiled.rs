use core::{
    error::Error,
    ops::{Deref, DerefMut},
    str::Utf8Error,
};
use std::collections::HashMap;

use crate::prelude::*;

/// A bundle of data for a yarn file as output from `ysc`. Useful for loading in
/// precompiled assets.
#[derive(Debug)]
pub struct CompiledFile {
    /// The [`Program`] associated with a single yarn file.
    pub program: Program,
    /// Compiled [`YscLine`] data. Typically converted to [`Line`]s using [`YscLine::to_string_table`]
    pub lines: Lines,
    /// Compiled [`MetadataLine`]s for a yarn file.
    pub metadata: Metadata,
}

#[derive(Debug)]
pub enum CsvParseError {
    BadLine(usize, usize, Option<String>),
    Utf8(Utf8Error),
}

impl core::fmt::Display for CsvParseError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            CsvParseError::BadLine(record_count, field_count, extra) => f.write_fmt(format_args!(
                "Could not parse CSV at line {record_count} field {field_count} {}",
                extra.as_ref().unwrap_or(&String::new())
            )),
            CsvParseError::Utf8(error) => f.write_str(&error.to_string()),
        }
    }
}
impl Error for CsvParseError {}

#[derive(Debug, PartialEq, Eq, Clone)]
pub struct YscLine {
    id: LineId,
    text: String,
    file: String,
    node: String,
    line_number: usize,
}

#[derive(Debug)]
struct Csv<const FIELDS: usize>(Vec<Vec<String>>);
impl<const FIELD_COUNT: usize> Csv<FIELD_COUNT> {
    fn from_bytes(bytes: &[u8]) -> core::result::Result<Self, CsvParseError> {
        let mut this = Self(vec![]);
        let mut reader = csv_core::Reader::new();
        let mut buf = vec![0u8; 1024];
        let mut out_len = 0;
        let mut input = bytes;
        let mut fields = vec![];
        let mut first_record = true;
        loop {
            let (res, nin, nout) = reader.read_field(input, &mut buf[out_len..]);
            out_len += nout;
            input = &input[nin..];
            match res {
                csv_core::ReadFieldResult::InputEmpty => {}
                csv_core::ReadFieldResult::OutputFull => {
                    buf.resize(buf.len() * 2, 0);
                }
                csv_core::ReadFieldResult::Field { record_end } => {
                    let res = core::str::from_utf8(&buf)
                        .map_err(CsvParseError::Utf8)?
                        .to_owned();
                    fields.push(res);
                    out_len = 0;

                    if record_end {
                        if first_record {
                            // skip the header
                            fields.clear();
                            first_record = false;
                            continue;
                        }
                        if fields.len() != FIELD_COUNT {
                            return Err(CsvParseError::BadLine(
                                this.0.len(),
                                fields.len(),
                                Some(format!(
                                    "Expected {FIELD_COUNT} fields, got {}",
                                    fields.len()
                                )),
                            ));
                        }
                        this.0.push(core::mem::take(&mut fields));
                    }
                }
                csv_core::ReadFieldResult::End => break,
            }
        }
        Ok(this)
    }
}

#[derive(Debug, Clone)]
pub struct Lines(Vec<YscLine>);
impl DerefMut for Lines {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}
impl Deref for Lines {
    type Target = Vec<YscLine>;
    fn deref(&self) -> &Self::Target {
        &self.0
    }
}
impl Lines {
    /// Loads line data from a file as generated by ysc, e.g. `hello_world-Lines.csv`
    pub fn from_bytes(input: &[u8]) -> core::result::Result<Lines, CsvParseError> {
        let csv = Csv::<5>::from_bytes(input)?;
        let mut this = Self(vec![]);
        let mut record_count = 0;
        for mut record in csv.0 {
            // guaranteed len of 5
            let mut record = record.iter_mut().rev();
            let mut next = || core::mem::take(record.next().take().unwrap());
            let line = YscLine {
                id: LineId(next()),
                text: next(),
                file: next(),
                node: next(),
                line_number: next().parse().map_err(|e: core::num::ParseIntError| {
                    CsvParseError::BadLine(record_count, 5, Some(e.to_string()))
                })?,
            };
            this.0.push(line);
            record_count += 1;
        }
        Ok(this)
    }
    #[cfg(feature = "std")]
    pub fn to_string_table(self) -> HashMap<LineId, String> {
        self.0
            .into_iter()
            .map(|line| (line.id, line.text))
            .collect()
    }
}

#[test]
fn test_line_parsing() {
    let bytes = r#"
id,text,file,node,lineNumber
line:123abc,"Hello World!",fake/path/hello_world.yarn,HelloWorld,3
"#;
    let lines = Lines::from_bytes(bytes.as_bytes()).unwrap();
    assert!(!lines.is_empty());
    assert_eq!(
        lines.first().unwrap(),
        &YscLine {
            id: LineId("line:123abc".to_string()),
            text: "Hello World!".to_string(),
            file: "fake/path/hello_world.yarn".to_string(),
            node: "HelloWorld".to_string(),
            line_number: 3
        }
    );
}

#[derive(Debug, PartialEq, Clone)]
pub struct MetadataLine {
    id: LineId,
    node: String,
    line_number: usize,
    tags: Vec<String>, // space-separated
}

#[derive(Debug, Clone)]
pub struct Metadata(Vec<MetadataLine>);
impl core::ops::DerefMut for Metadata {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}

impl core::ops::Deref for Metadata {
    type Target = Vec<MetadataLine>;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}
impl Metadata {
    pub fn from_bytes(bytes: &[u8]) -> core::result::Result<Self, CsvParseError> {
        let csv = Csv::<4>::from_bytes(bytes)?;
        let mut this = Self(vec![]);
        let mut record_count = 0;
        for mut record in csv.0 {
            let mut record = record.iter_mut().rev();
            let mut next = || core::mem::take(record.next().take().unwrap());
            let id = LineId(next());
            let node = next();
            let line_number = next().parse().map_err(|e: core::num::ParseIntError| {
                CsvParseError::BadLine(record_count, 4, Some(e.to_string()))
            })?;
            let tags_raw = next();
            let tags = if tags_raw.is_empty() {
                vec![]
            } else {
                tags_raw.split_whitespace().map(|s| s.to_string()).collect()
            };
            let line = MetadataLine {
                id,
                node,
                line_number,
                tags,
            };
            this.0.push(line);
            record_count += 1;
        }
        Ok(this)
    }
}

#[test]
fn test_metadata_parsing() {
    let bytes = r#"
id,node,lineNumber,tags
line:123abc,Start,3,a b c
"#;
    let metadata = Metadata::from_bytes(bytes.as_bytes()).unwrap();
    assert!(!metadata.is_empty());
    assert_eq!(
        metadata.first().unwrap(),
        &MetadataLine {
            id: LineId("line:123abc".to_string()),
            node: "Start".to_string(),
            line_number: 3,
            tags: ["a", "b", "c"].iter().map(|s| s.to_string()).collect()
        }
    );
}

#[test]
fn test_metadata_no_tags() {
    let bytes = r#"
id,node,lineNumber,tags
line:123abc,Start,3,
"#;
    let metadata = Metadata::from_bytes(bytes.as_bytes()).unwrap();
    assert!(!metadata.is_empty());
    assert_eq!(
        metadata.first().unwrap(),
        &MetadataLine {
            id: LineId("line:123abc".to_string()),
            node: "Start".to_string(),
            line_number: 3,
            tags: vec![],
        }
    );
}
