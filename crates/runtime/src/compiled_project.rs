use core::{
    error::Error,
    ops::{Deref, DerefMut},
    str::FromStr,
};

use alloc::collections::BTreeMap;

use crate::prelude::*;

pub struct CompiledProject {
    program: Program,
    lines: Vec<(LineId, String)>,
    metadata: BTreeMap<LineId, Vec<String>>,
}

#[derive(Debug)]
pub enum ProjectReaderError {
    Other(Box<dyn Error>),
    BadLine(usize, usize, Option<String>),
}

impl std::fmt::Display for ProjectReaderError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            ProjectReaderError::BadLine(record_count, field_count, extra) => {
                f.write_fmt(format_args!(
                    "Could not parse CSV at line {record_count} field {field_count} {}",
                    extra.as_ref().unwrap_or(&String::new())
                ))
            }
            ProjectReaderError::Other(error) => f.write_str(&error.to_string()),
        }
    }
}
impl Error for ProjectReaderError {}

#[derive(Debug, PartialEq, Eq)]
pub struct Line {
    id: LineId,
    text: String,
    file: String,
    node: String,
    line_number: usize,
}

#[derive(Debug)]
pub struct Lines(Vec<Line>);
impl DerefMut for Lines {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}
impl Deref for Lines {
    type Target = Vec<Line>;
    fn deref(&self) -> &Self::Target {
        &self.0
    }
}
impl Lines {
    /// Loads line data from a file as generated by ysc, e.g. `hello_world-Lines.csv`
    pub fn from_bytes(input: &[u8]) -> std::result::Result<Lines, ProjectReaderError> {
        std::println!("hi");
        let mut this = Self(vec![]);
        let mut reader = csv_core::Reader::new();
        let mut buf = vec![0u8; 1024];
        let mut out_len = 0;
        let mut input = input;
        let mut record_count = 0;
        let mut field_count = 0;
        let mut fields = vec![];
        loop {
            let (res, nin, nout) = reader.read_field(input, &mut buf[out_len..]);
            out_len += nout;
            input = &input[nin..];
            match res {
                csv_core::ReadFieldResult::InputEmpty => {}
                csv_core::ReadFieldResult::OutputFull => {
                    buf.resize(buf.len() * 2, 0);
                    std::println!("resized, vec length now {}", buf.len());
                }
                csv_core::ReadFieldResult::Field { record_end } => {
                    let res = String::from_utf8(buf[..out_len].to_vec())
                        .map_err(|e| ProjectReaderError::Other(Box::new(e)))?;
                    fields.push(res);
                    field_count += 1;
                    out_len = 0;

                    if record_end {
                        if record_count == 0 {
                            // skip the header
                            fields.clear();
                            record_count += 1;
                            field_count = 0;
                            continue;
                        }
                        if fields.len() != 5 {
                            return Err(ProjectReaderError::BadLine(
                                record_count,
                                field_count,
                                Some(format!("Expected 5 fields, got {}", fields.len())),
                            ));
                        }
                        fields.reverse();
                        let mut next_line = || {
                            fields.pop().ok_or(ProjectReaderError::BadLine(
                                record_count,
                                field_count,
                                None,
                            ))
                        };
                        let line = Line {
                            id: LineId(next_line()?),
                            text: next_line()?,
                            file: next_line()?,
                            node: next_line()?,
                            line_number: next_line()?.parse().map_err(
                                |e: core::num::ParseIntError| {
                                    ProjectReaderError::BadLine(
                                        record_count,
                                        field_count,
                                        Some(e.to_string()),
                                    )
                                },
                            )?,
                        };
                        this.0.push(line);
                        record_count += 1;
                        field_count = 0;
                    }
                }
                csv_core::ReadFieldResult::End => break,
            }
        }
        std::println!("done. got:\n{this:?}");
        Ok(this)
    }
}

#[test]
fn test_line_parsing() {
    let bytes = r#"
id,text,file,node,lineNumber
line:123abc,"Hello World!",fake/path/hello_world.yarn,HelloWorld,3
"#;
    let lines = Lines::from_bytes(bytes.as_bytes()).unwrap();
    assert!(!lines.is_empty());
    assert_eq!(
        lines.first().unwrap(),
        &Line {
            id: LineId("line:123abc".to_string()),
            text: "Hello World!".to_string(),
            file: "fake/path/hello_world.yarn".to_string(),
            node: "HelloWorld".to_string(),
            line_number: 3
        }
    );
}
