pub struct CompiledProject {
    program: Program,
    lines: Vec<(LineId, String)>,
    metadata: BTreeMap<LineId, Vec<String>>,
}

#[derive(Debug)]
pub enum CsvParseError {
    BadLine(usize, usize, Option<String>),
    Utf8(FromUtf8Error),
}

impl std::fmt::Display for CsvParseError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            CsvParseError::BadLine(record_count, field_count, extra) => f.write_fmt(format_args!(
                "Could not parse CSV at line {record_count} field {field_count} {}",
                extra.as_ref().unwrap_or(&String::new())
            )),
            CsvParseError::Utf8(error) => f.write_str(&error.to_string()),
        }
    }
}
impl Error for CsvParseError {}

#[derive(Debug, PartialEq, Eq)]
pub struct Line {
    id: LineId,
    text: String,
    file: String,
    node: String,
    line_number: usize,
}

pub struct Csv<const FIELDS: usize>(Vec<Vec<String>>);
impl<const FIELD_COUNT: usize> Csv<FIELD_COUNT> {
    fn from_bytes(bytes: &[u8]) -> std::result::Result<Self, CsvParseError> {
        let mut this = Self(vec![]);
        let mut reader = csv_core::Reader::new();
        let mut buf = vec![0u8; 1024];
        let mut out_len = 0;
        let mut input = bytes;
        let mut fields = vec![];
        let mut first_record = true;
        loop {
            let (res, nin, nout) = reader.read_field(input, &mut buf[out_len..]);
            out_len += nout;
            input = &input[nin..];
            match res {
                csv_core::ReadFieldResult::InputEmpty => {}
                csv_core::ReadFieldResult::OutputFull => {
                    buf.resize(buf.len() * 2, 0);
                    std::println!("resized, vec length now {}", buf.len());
                }
                csv_core::ReadFieldResult::Field { record_end } => {
                    let res = String::from_utf8(buf[..out_len].to_vec())
                        .map_err(|e| CsvParseError::Utf8(e))?;
                    fields.push(res);
                    out_len = 0;

                    if record_end {
                        if first_record {
                            // skip the header
                            fields.clear();
                            first_record = false;
                            continue;
                        }
                        if fields.len() != FIELD_COUNT {
                            return Err(CsvParseError::BadLine(
                                this.0.len(),
                                fields.len(),
                                Some(format!(
                                    "Expected {FIELD_COUNT} fields, got {}",
                                    fields.len()
                                )),
                            ));
                        }
                        this.0.push(fields.clone());
                        fields.clear();
                    }
                }
                csv_core::ReadFieldResult::End => break,
            }
        }
        Ok(this)
    }
}

#[derive(Debug)]
pub struct Lines(Vec<Line>);
impl DerefMut for Lines {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}
impl Deref for Lines {
    type Target = Vec<Line>;
    fn deref(&self) -> &Self::Target {
        &self.0
    }
}
impl Lines {
    /// Loads line data from a file as generated by ysc, e.g. `hello_world-Lines.csv`
    pub fn from_bytes(input: &[u8]) -> std::result::Result<Lines, CsvParseError> {
        let csv = Csv::<5>::from_bytes(input)?;
        let mut this = Self(vec![]);
        let mut record_count = 0;
        for mut record in csv.0 {
            // guaranteed len of 5
            record.reverse();
            let mut next = || record.pop().unwrap();
            let line = Line {
                id: LineId(next()),
                text: next(),
                file: next(),
                node: next(),
                line_number: next().parse().map_err(|e: core::num::ParseIntError| {
                    CsvParseError::BadLine(record_count, 5, Some(e.to_string()))
                })?,
            };
            this.0.push(line);
            record_count += 1;
        }
        Ok(this)
    }
}

#[test]
fn test_line_parsing() {
    let bytes = r#"
id,text,file,node,lineNumber
line:123abc,"Hello World!",fake/path/hello_world.yarn,HelloWorld,3
"#;
    let lines = Lines::from_bytes(bytes.as_bytes()).unwrap();
    assert!(!lines.is_empty());
    assert_eq!(
        lines.first().unwrap(),
        &Line {
            id: LineId("line:123abc".to_string()),
            text: "Hello World!".to_string(),
            file: "fake/path/hello_world.yarn".to_string(),
            node: "HelloWorld".to_string(),
            line_number: 3
        }
    );
}
